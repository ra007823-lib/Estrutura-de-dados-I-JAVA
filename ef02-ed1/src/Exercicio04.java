
public class Exercicio04 {

	public static void main(String[] args) {
		int contador = 10;
		contador++;
		System.out.println(contador);
		contador--;
		System.out.println(contador);
		contador+=5;
		System.out.println(contador);
		contador-=3;
		System.out.println(contador);
		contador*=2;
		System.out.println(contador);
		contador/=4;
		System.out.println(contador);
		contador%=3;
		System.out.println(contador);
		
				
	}

}
